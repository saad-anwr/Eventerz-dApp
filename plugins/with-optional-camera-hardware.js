/**
 * Declare the camera as optional hardware.
 *
 * # The bug this fixes
 *
 * Nothing in this project declares a `<uses-feature>` element - not `app.json`,
 * not `expo-camera`, not `expo-image-picker`, not any other dependency. That
 * sounds like the neutral default. It is not.
 *
 * Google Play *infers* hardware requirements from the permissions an app asks
 * for. Declaring `android.permission.CAMERA` and saying nothing else makes Play
 * behave as though the manifest read:
 *
 *   <uses-feature android:name="android.hardware.camera" android:required="true" />
 *   <uses-feature android:name="android.hardware.camera.autofocus" android:required="true" />
 *
 * The consequences are the kind that never show up on a developer's device:
 *
 *   * Play filters the listing off every device without a camera - and off some
 *     with one, because `camera.autofocus` is a stricter claim than `camera`.
 *   * The store page tells a reader the app cannot run without a camera.
 *
 * Both are false. Eventerz is an event app: discovery, RSVP, tickets, the
 * wallet, messaging and the whole attendee side never open the camera. The
 * camera has exactly one caller, `app/scan.tsx`, which is the organizer's
 * check-in screen - and even that screen ships a manual code-entry path that is
 * always visible, precisely because a camera cannot be assumed to work. An app
 * whose entire attendee experience runs without a camera must not be delisted
 * from a device for not having one.
 *
 * # Why this is the review answer, not a nicety
 *
 * The reviewer's decision flow starts at "can you provide functionality without
 * declaring permissions?". For CAMERA the honest answer is *mostly* - every
 * feature but one, and that one degrades to manual entry. There is no way to
 * express "mostly" in a permission, because a permission is binary. `required="false"`
 * is where that answer belongs: it keeps the permission for the screen that
 * needs it while telling Play the app stands up without the hardware, and it
 * moves the decision from install time to runtime, where `scan.tsx` already
 * handles it.
 *
 * # Why a config plugin rather than editing the manifest
 *
 * `android/` is gitignored and regenerated by `expo prebuild`, which EAS runs on
 * every build - the same reasoning as `with-solana-wallet-queries.js`. A
 * hand-edit survives locally and vanishes in CI, which for a Play-filtering bug
 * means the APK on the developer's machine is installable everywhere and the one
 * in the store is not.
 */

const { withAndroidManifest } = require('expo/config-plugins');

/**
 * The two features Play infers from `android.permission.CAMERA`.
 *
 * `autofocus` is on the list because the inference is not one-to-one: the
 * permission implies both, and declaring only `android.hardware.camera` leaves
 * the autofocus requirement in place, still filtering fixed-focus devices.
 */
const IMPLIED_CAMERA_FEATURES = [
  'android.hardware.camera',
  'android.hardware.camera.autofocus',
];

/**
 * Force every implied camera feature to `required="false"`.
 *
 * Existing entries are rewritten rather than skipped. A duplicate `<uses-feature>`
 * for the same name is merged by OR-ing `required`, so a stray `true` left in
 * place by another plugin would win over anything appended after it.
 *
 * Exported for the test; the plugin below is the only production caller.
 */
function markCameraOptional(manifest) {
  const features = (manifest['uses-feature'] ??= []);

  for (const name of IMPLIED_CAMERA_FEATURES) {
    const existing = features.find(
      (feature) => feature?.$?.['android:name'] === name,
    );

    if (existing) {
      existing.$['android:required'] = 'false';
    } else {
      features.push({
        $: { 'android:name': name, 'android:required': 'false' },
      });
    }
  }

  return manifest;
}

/*
 * A function declaration with properties hung off it, rather than an arrow
 * assigned to `module.exports` and extended afterwards. Expo needs the module's
 * export to *be* the plugin, and `tsc` only reads the extra exports off a
 * function it can see them attached to - writing `module.exports.x = ...` after
 * `module.exports = fn` typechecks as though the properties do not exist.
 */
function withOptionalCameraHardware(config) {
  return withAndroidManifest(config, (cfg) => {
    markCameraOptional(cfg.modResults.manifest);
    return cfg;
  });
}

withOptionalCameraHardware.markCameraOptional = markCameraOptional;
withOptionalCameraHardware.IMPLIED_CAMERA_FEATURES = IMPLIED_CAMERA_FEATURES;

module.exports = withOptionalCameraHardware;
