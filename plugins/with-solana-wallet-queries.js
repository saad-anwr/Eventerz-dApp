/**
 * Android package visibility for Mobile Wallet Adapter.
 *
 * # The bug this fixes
 *
 * Connecting a wallet failed on real devices - a Seeker with wallets installed -
 * while Google sign-in worked perfectly. The errors reaching users were
 * `java.util.concurrent.CancellationException` and, downstream of the null
 * address that produced, `Cannot read property 'slice' of null`. It is what the
 * Solana dApp Store rejection meant by "we could not complete the account access
 * or onboarding flow".
 *
 * The cause is Android 11 (API 30) package visibility. Since then an app cannot
 * see, query or launch another app unless it declares that intent in a
 * `<queries>` element. Mobile Wallet Adapter associates with a wallet by
 * resolving a `solana-wallet://` intent - so with no declaration,
 * `PackageManager` returns an empty list, every wallet on the device is
 * invisible, and the association is cancelled before any wallet is ever asked.
 *
 * Two things hid this:
 *
 *   * `@solana-mobile/mobile-wallet-adapter-protocol` ships an **empty**
 *     `AndroidManifest.xml`, so nothing is contributed by manifest merging. The
 *     declaration is the app's job and there is no build-time complaint when it
 *     is missing.
 *   * Google sign-in kept working throughout, because it opens an `https` URL
 *     in a Custom Tab and `https` *is* already declared (expo-web-browser adds
 *     it). So the one auth path that was declared worked and the one that was
 *     not silently found nothing - which reads as "the wallet is broken" rather
 *     than "the app cannot see it".
 *
 * # Why a config plugin rather than editing the manifest
 *
 * `android/` is gitignored and regenerated by `expo prebuild`, which EAS runs on
 * every build. A hand-edit to `AndroidManifest.xml` survives locally, disappears
 * in CI, and produces an APK that behaves differently from the one on the
 * developer's machine - the worst possible shape for this particular bug, since
 * it would appear fixed right up until it shipped.
 */

const { withAndroidManifest } = require('expo/config-plugins');

/**
 * The scheme every MWA-compatible wallet registers. This is the association
 * intent MWA resolves; without it the protocol has nothing to talk to.
 */
const WALLET_SCHEME = 'solana-wallet';

/** True when `queries` already declares an intent for this scheme. */
function hasWalletQuery(queries) {
  return queries.some((query) =>
    (query.intent ?? []).some((intent) =>
      (intent.data ?? []).some(
        (data) => data?.$?.['android:scheme'] === WALLET_SCHEME,
      ),
    ),
  );
}

const withSolanaWalletQueries = (config) =>
  withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;

    manifest.queries ??= [];
    if (hasWalletQuery(manifest.queries)) return cfg;

    /*
     * Appended as its own `<queries>` element rather than merged into the
     * existing one. Android allows several and unions them, and the block
     * already present is generated by other config plugins - writing into it
     * would put this declaration at the mercy of whatever regenerates it.
     */
    manifest.queries.push({
      intent: [
        {
          action: [
            { $: { 'android:name': 'android.intent.action.VIEW' } },
          ],
          category: [
            { $: { 'android:name': 'android.intent.category.BROWSABLE' } },
          ],
          data: [{ $: { 'android:scheme': WALLET_SCHEME } }],
        },
      ],
    });

    return cfg;
  });

module.exports = withSolanaWalletQueries;
